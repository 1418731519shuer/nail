function readKeyTxt(txtPath) {
  try {
    const val = fs.readFileSync(txtPath, 'utf-8').trim()
    if (val && !val.startsWith('#') && val !== '在此填写你的DeepSeek API Key') return val
  } catch { }
  return ''
}
function loadEnv(envPath) {
  try {
    return fs.readFileSync(envPath, 'utf-8').split('\n').reduce((acc, line) => {
      const m = line.match(/^(\w+)\s*=\s*"?([^"]*)"?$/)
      if (m) acc[m[1]] = m[2]
      return acc
    }, {})
  } catch { return {} }
}
