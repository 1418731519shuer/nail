// POST /api/recommend-slots/:position/refresh — 单槽重新选款
// 保持原 slot_type，从候选池排除已用款式重新抓一个（已锁定则报错）
app.post('/api/recommend-slots/:position/refresh', (req, res) => {
  const pos = parseInt(req.params.position)
  if (pos < 1 || pos > 8) return res.status(400).json({ error: 'position must be 1-8' })
  const slot = stylesDb.prepare('SELECT * FROM recommend_slots WHERE position=?').get(pos)
  if (!slot) return res.status(404).json({ error: '坑位不存在，请先生成一轮推荐' })
  if (slot.locked) return res.status(400).json({ error: `P${pos} 已锁定，请先解锁再刷新` })

  // 排除当前8个坑位已有的款式（不能重复）
  const allUsed = stylesDb.prepare('SELECT style_id FROM recommend_slots WHERE style_id IS NOT NULL AND position!=?').all(pos).map(r => r.style_id)
  const picked = pickStyleForSlot(slot.slot_type, allUsed, '')
  if (!picked) return res.status(404).json({ error: `${slot.slot_type} 候选池已无可用款式` })

  stylesDb.prepare(`UPDATE recommend_slots SET style_id=?, is_manual=0, updated_at=datetime('now'), updated_by='ai' WHERE position=?`).run(picked.id, pos)
  auditLog('recommend.refreshSlot', { position: pos, oldStyleId: slot.style_id, newStyleId: picked.id }, { ok: true })
  res.json({ ok: true, position: pos, oldStyleId: slot.style_id, newStyleId: picked.id })
})

// POST /api/recommend-slots/fill-empty — 补全所有 style_id=NULL 的空坑位
// 锁定坑位也跳过；已有款式坑位不动
app.post('/api/recommend-slots/fill-empty', (req, res) => {
  const { intentText = '' } = req.body
  const emptySlots = stylesDb.prepare(`SELECT * FROM recommend_slots WHERE style_id IS NULL AND locked=0 ORDER BY position`).all()
  if (!emptySlots.length) return res.json({ ok: true, filled: [] })

  const usedIds = stylesDb.prepare('SELECT style_id FROM recommend_slots WHERE style_id IS NOT NULL').all().map(r => r.style_id)
  const filled = stylesDb.transaction(() => {
    const results = []
    for (const slot of emptySlots) {
      const picked = pickStyleForSlot(slot.slot_type, usedIds, intentText)
      if (picked) {
        usedIds.push(picked.id)
        stylesDb.prepare(`UPDATE recommend_slots SET style_id=?, is_manual=0, updated_at=datetime('now'), updated_by='ai' WHERE position=?`).run(picked.id, slot.position)
        results.push({ position: slot.position, slot_type: slot.slot_type, style_id: picked.id })
      } else {
        results.push({ position: slot.position, slot_type: slot.slot_type, style_id: null, failed: true })
      }
    }
    return results
  })()
  auditLog('recommend.fillEmpty', { intentText }, { filled })
  res.json({ ok: true, filled })
})

