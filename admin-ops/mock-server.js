// ── 启动时把 weekly CSV 最新一周的分数同步到 styles.db ──────────────
;(function syncWeeklyScores() {
  const csvPath = path.join(SIM_DIR, 'xhs_simulated_nail_style_weekly_metrics.csv')
  if (!fs.existsSync(csvPath)) { console.warn('[sync] weekly CSV 不存在，跳过分数同步'); return }

  const lines = fs.readFileSync(csvPath, 'utf-8').replace(/^﻿/, '').split('\n').filter(Boolean)
  const header = lines[0].split(',')
  const col = (name) => header.indexOf(name)

  // 找最新 week_idx
  let maxWeek = -1
  for (let i = 1; i < lines.length; i++) {
    const w = parseInt(lines[i].split(',')[col('week_idx')])
    if (w > maxWeek) maxWeek = w
  }

  // 取最新一周每款数据
  const latest = {}
  for (let i = 1; i < lines.length; i++) {
    const vals = lines[i].split(',')
    if (parseInt(vals[col('week_idx')]) !== maxWeek) continue
    latest[vals[col('style_id')]] = {
      hot_score:        parseFloat(vals[col('hot_score')]),
      cold_risk_score:  parseFloat(vals[col('cold_risk_score')]),
      growth_score:     parseFloat(vals[col('growth_score')]),
    }
  }

  const update = stylesDb.prepare(`
    UPDATE styles SET hot_score=?, cold_risk_score=?, growth_score=?, updated_at=datetime('now')
    WHERE id=?
  `)
  const sync = stylesDb.transaction(() => {
    let n = 0
    for (const [id, scores] of Object.entries(latest)) {
      const r = update.run(scores.hot_score, scores.cold_risk_score, scores.growth_score, id)
      if (r.changes) n++
    }
    return n
  })
  const synced = sync()
  console.log(`[sync] weekly week=${maxWeek} → styles.db 已同步 ${synced} 款 hot/cold/growth 分数`)
})()

