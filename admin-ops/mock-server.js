function buildAggContext() {
  const byStatus = stylesDb.prepare(`SELECT status, COUNT(*) as n FROM styles GROUP BY status`).all()
  const byBucket = stylesDb.prepare(`SELECT recommend_bucket, COUNT(*) as n FROM styles GROUP BY recommend_bucket`).all()
  const metrics = stylesDb.prepare(`
    SELECT COUNT(*) as total,
      ROUND(AVG(hot_score),3) as avg_hot,
      ROUND(AVG(cold_risk_score),3) as avg_cold,
      ROUND(AVG(tryon_confirm_rate),3) as avg_conv,
      SUM(view_uv) as total_view,
      SUM(tryon_uv) as total_tryon,
      SUM(confirm_uv) as total_confirm
    FROM styles WHERE status='published'
  `).get()
  const slots = stylesDb.prepare(`
    SELECT rs.position, s.name as styleName, s.hot_score
    FROM recommend_slots rs LEFT JOIN styles s ON rs.style_id = s.id
    ORDER BY rs.position
  `).all()

  const statusMap = Object.fromEntries(byStatus.map(r => [r.status, r.n]))
  const bucketMap = Object.fromEntries(byBucket.map(r => [r.recommend_bucket, r.n]))

  return `
【当前运营快照】
- 款式库存：上架 ${statusMap.published || 0} / 下架 ${statusMap.unpublished || 0} / 归档 ${statusMap.archived || 0}
- 热度分布：hot=${bucketMap.hot || 0} / potential=${bucketMap.potential || 0} / cold=${bucketMap.cold || 0} / stable=${bucketMap.stable || 0}
- 全库指标（上架款）：平均热度=${metrics.avg_hot} 平均冷门风险=${metrics.avg_cold} 平均转化率=${metrics.avg_conv}
- 总曝光=${metrics.total_view} 总试戴=${metrics.total_tryon} 总确认=${metrics.total_confirm}
- 推荐位：${slots.map(s => `P${s.position}=${s.styleName || '空'}`).join(' / ')}`
}

function buildSystemContent(mode, modeHint, opsContext) {
  const aggCtx = buildAggContext()
  if (mode === 'chat') {
    return modeHint || CHAT_SYSTEM
  }
  if (mode === 'insight') {
    return (modeHint || INSIGHT_SYSTEM) + '\n\n' + aggCtx
  }
  if (mode === 'action') {
    return ACTION_STATIC + '\n\n' + aggCtx
  }
  return CHAT_SYSTEM
}

