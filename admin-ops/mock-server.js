/**
 * 候选池视图（已在 DB 中定义，status='published' 已过滤，分数降序）：
 *   v_pool_hot      → hot_score DESC
 *   v_pool_potential→ growth_score DESC
 *   v_pool_cold     → cold_risk_score DESC
 *   v_pool_adaptive → tryon_confirm_rate DESC（基础兜底，待接入用户偏好打分）
 *
 * 兜底链（候选池耗尽时按序降级）：
 *   hot      → v_pool_hot → v_pool_potential → v_pool_adaptive
 *   potential→ v_pool_potential → v_pool_hot → v_pool_adaptive
 *   cold     → v_pool_cold → v_pool_adaptive（不走热门，避免好款浪费在观察位）
 *   adaptive → keyword 匹配 → v_pool_adaptive → v_pool_hot
 */
function pickStyleForSlot(slotType, excludeIds = [], intentKeywords = '') {
  const ex = excludeIds.length
    ? `WHERE id NOT IN (${excludeIds.map(() => '?').join(',')})`
    : ''

  // 从指定候选池取第一个未用款
  function fromPool(view) {
    return stylesDb.prepare(`SELECT id FROM ${view} ${ex} LIMIT 1`).get(...excludeIds)
  }

  if (slotType === 'hot')
    return fromPool('v_pool_hot')
        || fromPool('v_pool_potential')   // 兜底：增长最快的潜力款
        || fromPool('v_pool_adaptive')    // 兜底：任意高转化在架款

  if (slotType === 'potential')
    return fromPool('v_pool_potential')
        || fromPool('v_pool_hot')         // 兜底：热门款
        || fromPool('v_pool_adaptive')

  if (slotType === 'cold')
    return fromPool('v_pool_cold')
        || fromPool('v_pool_adaptive')    // 冷门位不走热门兜底

  // adaptive：关键词多维匹配 → 候选池兜底
  // TODO: 接入用户端 stylePref/typePref/shapePref/seasonPref 后替换为多维打分 SQL
  if (intentKeywords) {
    const ex2 = excludeIds.length ? `AND id NOT IN (${excludeIds.map(() => '?').join(',')})` : ''
    const kws = intentKeywords.split(/[，,\s]+/).filter(Boolean)
    for (const kw of kws) {
      const row = stylesDb.prepare(`
        SELECT id FROM styles WHERE status='published'
        AND (name LIKE ? OR category LIKE ? OR tags_style LIKE ?
             OR tags_color LIKE ? OR primary_tag LIKE ?) ${ex2}
        ORDER BY tryon_confirm_rate DESC LIMIT 1
      `).get(...Array(5).fill(`%${kw}%`), ...excludeIds)
      if (row) return row
    }
  }
  return fromPool('v_pool_adaptive')
      || fromPool('v_pool_hot')
}

