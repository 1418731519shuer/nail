app.post('/api/styles/query', (req, res) => {
  const ALLOWED_FIELDS = new Set([
    'id','style_code','name','description','author','source_url','cover_image',
    'status','is_promoted','is_cold_start','recommend_bucket','trend_label',
    'listed_at','unpublished_at','price','makeable',
    'hot_score','cold_risk_score','growth_score','view_uv','tryon_uv','want_uv',
    'confirm_uv','tryon_confirm_rate',
    'xhs_likes','xhs_saves','xhs_comments','xhs_shares',
    'category','primary_tag','secondary_tag','tags_style','tags_color','tags_season','tags_shape',
    'crawled','created_at','updated_at','thumb','accent','nail_gradient'
  ])
  const OP_MAP = { eq:'=', ne:'!=', gt:'>', lt:'<', gte:'>=', lte:'<=', like:'LIKE', in:'IN' }
  const { filters = [], sort, limit = 50, fields = [] } = req.body
  const where = []
  const params = []
  for (const f of filters) {
    if (!ALLOWED_FIELDS.has(f.field)) continue
    const sqlOp = OP_MAP[f.op]
    if (!sqlOp) continue
    if (f.op === 'in') {
      if (!Array.isArray(f.value) || !f.value.length) continue
      where.push(`${f.field} IN (${f.value.map(() => '?').join(',')})`)
      params.push(...f.value)
    } else if (f.op === 'like') {
      where.push(`${f.field} LIKE ?`)
      params.push(`%${f.value}%`)
    } else {
      where.push(`${f.field} ${sqlOp} ?`)
      params.push(f.value)
    }
  }
  const selectCols = (fields.length ? fields.filter(f => ALLOWED_FIELDS.has(f)) : ['*']).join(', ') || '*'
  let sql = `SELECT ${selectCols} FROM styles`
  if (where.length) sql += ` WHERE ${where.join(' AND ')}`
  if (sort && ALLOWED_FIELDS.has(sort.field)) {
    sql += ` ORDER BY ${sort.field} ${sort.dir === 'asc' ? 'ASC' : 'DESC'}`
  }
  sql += ` LIMIT ${Math.min(parseInt(limit) || 50, 200)}`
  try {
    const rows = stylesDb.prepare(sql).all(...params)
    res.json({ rows, count: rows.length })
  } catch (e) {
    res.status(400).json({ error: e.message })
  }
})

