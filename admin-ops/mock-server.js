// POST /api/recommend-slots/generate — 按策略自动生成一轮推荐
// body: { strategyId, intentText? }
// 所有策略（含 custom）的 slot_types 均从 recommend_strategies 表读取
app.post('/api/recommend-slots/generate', (req, res) => {
  const { strategyId = 'hot_first', intentText = '' } = req.body
  const strategy = stylesDb.prepare('SELECT slot_types FROM recommend_strategies WHERE id = ?').get(strategyId)
  if (!strategy) return res.status(400).json({ error: '未知策略 ' + strategyId })
  const slotPlan = JSON.parse(strategy.slot_types)

  const usedIds = []
  const reasons = {
    hot:      '热度分高，近期确认率稳定，适合主推位',
    potential:'增长分高，曝光不足，补量放大潜力款',
    cold:     '冷门观察位，验证是封面问题还是需求偏弱',
    adaptive: intentText ? `匹配用户偏好「${intentText.slice(0,20)}」` : '高试戴转化率，个性化匹配'
  }

  const upsert = stylesDb.prepare(`
    INSERT INTO recommend_slots(position, slot_type, style_id, strategy_id, reason, is_manual, locked, updated_at, updated_by)
    VALUES (?,?,?,?,?,0,0,datetime('now'),'ai')
    ON CONFLICT(position) DO UPDATE SET
      slot_type=excluded.slot_type, style_id=excluded.style_id, strategy_id=excluded.strategy_id,
      reason=excluded.reason, is_manual=0, updated_at=excluded.updated_at, updated_by='ai'
    WHERE locked=0
  `)

  const generated = stylesDb.transaction(() => {
    const results = []
    for (let i = 0; i < 8; i++) {
      const pos = i + 1
      // 已锁定的坑位跳过
      const existing = stylesDb.prepare('SELECT locked, style_id FROM recommend_slots WHERE position=?').get(pos)
      if (existing?.locked) { results.push({ position: pos, skipped: true, locked: true }); continue }

      const type = slotPlan[i]
      const picked = pickStyleForSlot(type, usedIds, intentText)
      const styleId = picked?.id || null
      if (styleId) usedIds.push(styleId)
      upsert.run(pos, type, styleId, strategyId, reasons[type])
      results.push({ position: pos, slot_type: type, style_id: styleId })
    }
    return results
  })()

  auditLog('recommend.generate', { strategyId, intentText }, { generated })
  res.json({ ok: true, strategyId, generated })
})

// PUT /api/recommend-slots/:position — 手动换款或改坑位类型
// body: { styleId?, slotType?, reason?, locked? }
app.put('/api/recommend-slots/:position', (req, res) => {
  const pos = parseInt(req.params.position)
  if (pos < 1 || pos > 8) return res.status(400).json({ error: 'position must be 1-8' })
  const { styleId, slotType, reason, locked } = req.body

  const current = stylesDb.prepare('SELECT * FROM recommend_slots WHERE position=?').get(pos)
  const updates = []
  const vals = []
  if (styleId !== undefined) {
    const s = stylesDb.prepare('SELECT id FROM styles WHERE id=?').get(styleId)
    if (!s) return res.status(404).json({ error: 'style not found' })
    updates.push('style_id=?', 'is_manual=1'); vals.push(styleId)
  }
  if (slotType !== undefined) { updates.push('slot_type=?'); vals.push(slotType) }
  if (reason !== undefined)   { updates.push('reason=?'); vals.push(reason) }
  if (locked !== undefined)   { updates.push('locked=?'); vals.push(locked ? 1 : 0) }
  updates.push("updated_at=datetime('now')", "updated_by='operator'")
  vals.push(pos)

  if (current) {
    stylesDb.prepare(`UPDATE recommend_slots SET ${updates.join(',')} WHERE position=?`).run(...vals)
  } else {
    stylesDb.prepare(`
      INSERT INTO recommend_slots(position,slot_type,style_id,strategy_id,reason,is_manual,locked,updated_at,updated_by)
      VALUES(?,?,?,?,?,1,0,datetime('now'),'operator')
    `).run(pos, slotType || 'hot', styleId || null, 'custom', reason || '手动调整', )
  }
  auditLog('recommend.set', { position: pos, styleId, slotType }, { ok: true })
  res.json({ ok: true, position: pos })
})

